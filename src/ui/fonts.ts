// Stillframe's two bitmap faces, drawn for this game (docs/STYLE.md §8). They replace the old 3×5 and
// 5×7 capitals: the brief was "clear to read, the opposite of Last Watt" (thin pale capitals on dark
// slate), so these are heavy, mixed case, and meant for dark ink on white paper.
//
//   Pane   the body face: cap 8, x-height 6, descenders 2. 2 px verticals, 1 px horizontals, square
//          bowls with the corners cut. Figures 6 wide and tabular.
//   Shard  the display face, capitals only: cap 11. 3 px verticals, 2 px horizontals, faceted corners
//          like the red glass. Titles, big numbers, banners. Figures 8 wide and tabular.
//
// A glyph is its rows top to bottom joined by '|', '#' ink and '.' paper, every row the same width. Row
// 0 is the cap line; the baseline is the last cap row and descenders hang below it. A lowercase letter
// starts with blank rows down to the x-height. Drawn in UI pixels (half a game pixel; src/ui/text.ts),
// or at one font pixel per game pixel for words painted on the floor.
//
// pixel-art/fonts/sheet.py renders a contact sheet of both faces straight from this file.

export interface FaceDef {
  name: string;
  /** cap height in font pixels */
  cap: number;
  /** blank columns between glyphs */
  gap: number;
  /** width of a space */
  space: number;
  /** distance from one baseline to the next */
  lineH: number;
  glyphs: Record<string, string>;
}

