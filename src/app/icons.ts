export function trackIcon(ctx: CanvasRenderingContext2D, id: TrackId, x: number, y: number) {
  const rows = ICONS[id];
  const colors: Record<string, string> = { '#': PAL.cyan, o: PAL.paper, '+': PAL.slate };
  rows.forEach((r, j) => {
    for (let i = 0; i < r.length; i++) {
      const c = colors[r[i]];
      if (!c) continue;
      ctx.fillStyle = c;
      ctx.fillRect(x + i, y + j, 1, 1);
    }
  });
}
